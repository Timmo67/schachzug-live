// Builds the puzzle selection from the lichess puzzle database (CC0, https://database.lichess.org/#puzzles).
// Reads the decompressed CSV on stdin, writes an SQL migration to stdout:
//   curl -sSL https://database.lichess.org/lichess_db_puzzle.csv.zst | zstd -dc | node scripts/build-puzzles.mjs > supabase/migrations/0013_puzzle_data.sql
// Picks well-tested, popular puzzles evenly across ratings so every player finds puzzles at their level.
// Runs in GitHub Actions (.github/workflows/puzzles.yml) because the database host is not reachable everywhere.
import { createInterface } from 'node:readline';

const MIN_RATING = 400, MAX_RATING = 2900, BIN = 50, PER_BIN = 60;
const bins = new Map();
const sqlText = (s) => `'${s.replace(/'/g, "''")}'`;
const sqlArray = (a) => `array[${a.map(sqlText).join(',')}]::text[]`;

const rl = createInterface({ input: process.stdin, crlfDelay: Infinity });
let header = true;
for await (const line of rl) {
  if (header) { header = false; continue; }
  // PuzzleId,FEN,Moves,Rating,RatingDeviation,Popularity,NbPlays,Themes,GameUrl,OpeningTags
  const [id, fen, moves, rating, dev, popularity, plays, themes] = line.split(',');
  const r = Number(rating), m = moves.split(' ');
  if (r < MIN_RATING || r >= MAX_RATING) continue;
  if (Number(dev) > 80 || Number(popularity) < 85 || Number(plays) < 1000) continue;
  if (m.length < 2 || m.length > 8) continue;
  const bin = Math.floor(r / BIN);
  const list = bins.get(bin) ?? [];
  if (list.length >= PER_BIN) continue;
  list.push({ id, fen, moves: m, rating: r, popularity: Number(popularity), themes: themes ? themes.split(' ') : [] });
  bins.set(bin, list);
}

const all = [...bins.keys()].sort((a, b) => a - b).flatMap((b) => bins.get(b));
const out = [
  '-- Generated by scripts/build-puzzles.mjs from the lichess puzzle database (CC0). Do not edit by hand.',
  `-- ${all.length} puzzles, ratings ${MIN_RATING}–${MAX_RATING}, up to ${PER_BIN} per ${BIN} rating points.`,
];
for (let i = 0; i < all.length; i += 500) {
  const rows = all.slice(i, i + 500).map((p) =>
    `(${sqlText(p.id)},${sqlText(p.fen)},${sqlArray(p.moves)},${p.rating},${p.popularity},${sqlArray(p.themes)})`);
  out.push(`insert into public.puzzles (id, fen, moves, rating, popularity, themes) values\n${rows.join(',\n')}\non conflict (id) do nothing;`);
}
process.stdout.write(out.join('\n') + '\n');
process.stderr.write(`selected ${all.length} puzzles\n`);
